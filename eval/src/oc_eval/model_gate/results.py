"""Gate results: the machine-readable run files, and the table generated from them (D9).

One file per run, `eval/results/model_gate/<model_id>__<llama_build>__<machine>.json`: per gate the
status, the measured value, the threshold and a sentence of detail; the machine descriptor; the
llama.cpp build tag; the date. Those files are the source of truth, and `docs/MODEL_GATE.md` is
rendered from them by `model_gate.py --render-table` and never edited by hand.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Literal

REPO_ROOT = Path(__file__).resolve().parents[4]
RESULTS_DIR = REPO_ROOT / "eval" / "results" / "model_gate"
TABLE_PATH = REPO_ROOT / "docs" / "MODEL_GATE.md"
SCHEMA = "openconvert.model_gate/1"
GATES = ("G1", "G2", "G3", "G4", "G5", "G6", "G7", "G8", "G9")

Status = Literal["pass", "fail", "not_run"]

# What each gate asks, in D9's words, for the table's first column.
QUESTIONS = {
    "G1": "loads, `/health` ok, `llama-bench` completes",
    "G2": "every grammar-constrained generation parses and passes its semantic assertions",
    "G3": "prompt renderer matches the reference tokenizer; thinking absent",
    "G4": "full per-book call set within the time budget and the wall-clock share",
    "G5": "a second identical call set costs at most a fraction of the first",
    "G6": "peak RSS within budget; memory released within seconds of kill",
    "G7": "McNemar non-inferior on all four tasks vs the incumbent, better on one",
    "G8": "DE and TR flat-enum probes, zero out-of-alphabet output",
    "G9": "GGUF reproducible from official safetensors with a SHA-256 we produced",
}


@dataclass
class GateResult:
    gate: str
    status: Status
    measured: Any = None
    threshold: Any = None
    detail: str = ""


@dataclass
class Run:
    model_id: str
    llama_build: str
    machine: str
    machine_descriptor: dict[str, Any]
    date: str
    gates: list[GateResult] = field(default_factory=list)
    schema: str = SCHEMA

    @property
    def verdict(self) -> Status:
        """Pass only when all nine gates pass. A gate that did not run is not a pass (D9: any
        failure keeps the model experimental)."""
        statuses = {g.gate: g.status for g in self.gates}
        return "pass" if all(statuses.get(g) == "pass" for g in GATES) else "fail"

    def file_name(self) -> str:
        return f"{self.model_id}__{self.llama_build}__{self.machine}.json"

    def to_json(self) -> str:
        data = asdict(self)
        data["verdict"] = self.verdict
        return json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def load(path: Path) -> Run:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise ValueError(f"{path.name}: schema {data.get('schema')!r}, expected {SCHEMA!r}")
    gates = [GateResult(**g) for g in data["gates"]]
    return Run(
        model_id=data["model_id"],
        llama_build=data["llama_build"],
        machine=data["machine"],
        machine_descriptor=data["machine_descriptor"],
        date=data["date"],
        gates=gates,
    )


def load_all(directory: Path = RESULTS_DIR) -> list[Run]:
    return [load(path) for path in sorted(directory.glob("*.json"))]


def table(run: Run) -> str:
    """The pass/fail table for one run, as printed and as rendered into MODEL_GATE.md."""
    lines = [
        "| Gate | Asks | Status | Measured | Threshold | Detail |",
        "|---|---|---|---|---|---|",
    ]
    by_gate = {g.gate: g for g in run.gates}
    for gate in GATES:
        result = by_gate.get(gate, GateResult(gate, "not_run", detail="no result recorded"))
        lines.append(
            f"| {gate} | {QUESTIONS[gate]} | **{result.status}** | {_cell(result.measured)} "
            f"| {_cell(result.threshold)} | {result.detail.replace('|', '/')} |"
        )
    return "\n".join(lines)


def _cell(value: Any) -> str:
    if value is None:
        return "—"
    return json.dumps(value, ensure_ascii=False) if not isinstance(value, str) else value


def render(runs: list[Run], thresholds_rows: list[tuple[str, Any, str]]) -> str:
    out = [
        "# Model promotion gate",
        "",
        "<!-- Generated by `eval/model_gate.py --render-table` from eval/results/model_gate/*.json."
        " Do not edit: D9 makes the result files the source of truth. -->",
        "",
        "A model becomes the default only when all nine gates of D9 pass on both reference",
        "machines, L (4c/8t AVX2 x86, 16 GB) and M (base Apple M-series, 16 GB), against the",
        "pinned llama.cpp build (`xtask/llama.lock`). Any failure, and any gate that did not run,",
        "keeps it `experimental`. The whole gate re-runs on every llama.cpp bump.",
        "",
        "## Thresholds",
        "",
        "| Key | Value | Source |",
        "|---|---|---|",
    ]
    out += [f"| `{key}` | {value} | {source} |" for key, value, source in thresholds_rows]
    out += ["", "## Runs", ""]
    if not runs:
        out += [
            "No gate run is recorded yet. A run needs a reference machine, the pinned llama-server",
            "and the model file; none of them was available where Phase 9 was built.",
        ]
    for run in runs:
        out += [
            f"### {run.model_id} · {run.llama_build} · {run.machine} · {run.date} — "
            f"**{run.verdict}**",
            "",
            table(run),
            "",
        ]
    return "\n".join(out).rstrip() + "\n"
