"""`docs/AI_EVALUATION.md`, rendered from the outcomes and the gold sets — never edited by hand."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from pathlib import Path

from oc_eval import thresholds
from oc_eval.compare import false_repair, gold, mcnemar

REPO_ROOT = Path(__file__).resolve().parents[4]
DOC_PATH = REPO_ROOT / "docs" / "AI_EVALUATION.md"
OUTCOMES_PATH = REPO_ROOT / "eval" / "data" / "ai_eval" / "outcomes.jsonl"


def render(
    outcomes: Sequence[false_repair.Outcome],
    gold_sets: Mapping[str, Sequence[gold.Item]],
    enabled: Mapping[str, Sequence[str]],
) -> str:
    rows = false_repair.table(outcomes)
    verdict = false_repair.gate(rows, enabled)
    out: list[str] = [
        "# AI evaluation",
        "",
        "<!-- Generated by `python -m oc_eval.compare --render` from",
        "     `eval/data/ai_eval/outcomes.jsonl` and `eval/data/gold/`.",
        "     Do not edit: `--check` holds this file equal to the render. -->",
        "",
        "PHASE 10 detail 7: each task, run deterministic-only and deterministic+LLM over the same",
        "assertions. `b` counts assertions only the LLM path passed, `c` those only the",
        "deterministic path passed — **false repairs**. McNemar's χ² is used when `b + c ≥ "
        f"{mcnemar.exact_below()}` and the exact binomial below it. A task is enabled-by-opt-in",
        "for a language only when it is non-inferior there "
        f"(one-sided α = {false_repair_param('ai_eval.alpha')}, margin "
        f"{false_repair_param('ai_eval.noninferiority_margin')}) and its false-repair rate "
        f"`c / n` is at most {false_repair.false_repair_max()} in every category.",
        "",
    ]
    if not outcomes:
        out += [
            "**No evaluation has run.** No model was reachable where Phase 10 was built "
            "(huggingface.co refused), so there are no paired outcomes, no McNemar table and no "
            "false-repair rate. Every task stays behind `--ai-all-tasks`: the language maps in "
            "`thresholds.toml` are empty.",
            "",
        ]

    out += ["## Gold sets", "", "| Task | Items | Strata | Needed |", "|---|---|---|---|"]
    for task in false_repair.TASKS:
        items = gold_sets.get(task, [])
        strata = sorted({item.stratum for item in items})
        out.append(
            f"| `{task}` | {len(items)} | {', '.join(strata) or '—'} | {gold.minimum()} per task, "
            "from the real strata (D18) |"
        )
    out += [""]

    out += [
        "## Language gate",
        "",
        "| Task | Enabled in `thresholds.toml` | Proposed by the evidence |",
        "|---|---|---|",
    ]
    for task in false_repair.TASKS:
        now = ", ".join(enabled.get(task, [])) or "none"
        proposed = ", ".join(false_repair.proposed_languages(rows, task)) or "none"
        out.append(f"| `{task}` | {now} | {proposed} |")
    out += [""]

    out += ["## Paired outcomes, per task, language and category", ""]
    if rows:
        out += [
            "| Task | Lang | Category | n | b | c | Test | χ² | p | False-repair rate | ≤ bound |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for row in rows:
            statistic = "—" if row.test.statistic is None else f"{row.test.statistic:.3f}"
            within = "yes" if row.false_repair_rate <= false_repair.false_repair_max() else "**no**"
            out.append(
                f"| `{row.task}` | {row.language} | {row.category} | {row.n} | {row.b} | {row.c} | "
                f"{row.test.method} | {statistic} | {row.test.p:.4f} | "
                f"{row.false_repair_rate:.4f} | {within} |"
            )
    else:
        out.append("None.")
    out += [""]

    out += ["## Gate (row 10.18)", ""]
    enabled_count = sum(len(languages) for languages in enabled.values())
    if verdict.passed:
        out.append(
            f"**Pass** — {enabled_count} task-language pairs enabled, every one within the bound."
            if enabled_count
            else "**Pass, vacuously** — no task is enabled for any language, so no enabled task "
            "can exceed the bound."
        )
    else:
        out.append("**Fail**:")
        out += ["", *[f"- {failure}" for failure in verdict.failures]]
    out.append("")
    return "\n".join(out)


def false_repair_param(key: str) -> str:
    return str(thresholds.value(key))


def render_committed() -> str:
    return render(
        false_repair.load(OUTCOMES_PATH),
        gold.load_all(),
        {task: false_repair.enabled_languages(task) for task in false_repair.TASKS},
    )
